// Generate the file:// edition from the same HTML/CSS/JS/data as GitHub Pages.
const fs = require('node:fs');
const path = require('node:path');
const webpack = require('webpack');
const root = path.resolve(__dirname, '..');
const pages = ['index.html', 'impressum.html', 'datenschutz.html', 'haftung.html', '404.html'];
const localName = (file) => (file === 'index.html' ? 'Lokal.html' : 'Lokal-' + file);
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');

async function buildLocal(output) {
  const bundleDir = path.join(root, 'dist', '.local-build');
  const compiler = webpack({
    mode: 'production',
    context: root,
    entry: './js/main.js',
    devtool: false,
    output: { path: bundleDir, filename: 'local.js', iife: true },
    module: {
      rules: [{ test: /\.js$/, include: [path.join(root, 'js'), path.join(root, 'data')], type: 'javascript/esm' }],
      parser: { javascript: { dynamicImportMode: 'eager' } },
    },
    optimization: { splitChunks: false, runtimeChunk: false },
    performance: { hints: false },
  });
  let stats;
  try {
    stats = await new Promise((resolve, reject) =>
      compiler.run((error, result) => (error ? reject(error) : resolve(result)))
    );
    if (stats.hasErrors()) throw new Error(stats.toString({ all: false, errors: true }));
    const assets = stats.toJson({ all: false, assets: true }).assets.map((a) => a.name);
    if (assets.length !== 1 || assets[0] !== 'local.js')
      throw new Error('Offline build must emit exactly one script: ' + assets.join(', '));
  } finally {
    await new Promise((resolve) => compiler.close(resolve));
  }
  const bundle = fs.readFileSync(path.join(bundleDir, 'local.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
  const json = JSON.stringify(JSON.parse(read('data/crystals.json'))).replace(/</g, '\\u003c');
  for (const file of pages) {
    let html = read(file)
      .replace(/\s*<!-- LOCAL-ENTRY:[\s\S]*?<!-- \/LOCAL-ENTRY -->/, '')
      .replace(/\s*<!-- HTTP-RESOURCES -->[\s\S]*?<!-- \/HTTP-RESOURCES -->/, '')
      .replace(/\s*<!-- HTTP-MODULES:[\s\S]*?<!-- \/HTTP-MODULES -->/, '')
      .replace(/<template id="http-resources">([\s\S]*?)<\/template>/, '$1')
      .replace(/\s*<base\b[^>]*>/gi, '')
      // Offline edition deliberately uses CSS system-font fallbacks (no Google requests).
      .replace(/\s*<link\b[^>]*(?:fonts\.googleapis\.com|fonts\.gstatic\.com)[^>]*>/gi, '')
      .replace(/\s*@import\s+url\(['"]https:\/\/fonts\.googleapis\.com[^'"\r\n]*['"]\);/gi, '')
      .replace(/\s*<link\b[^>]*rel="preload"[^>]*>/gi, '')
      // Stylesheet refs are inlined regardless of attribute order / line wrapping
      // (the HTML is Prettier-formatted, so tags may span several lines and end in "/>").
      .replace(/<link\b[^>]*\brel="stylesheet"[^>]*>/gi, (tag) => {
        const href = /\bhref="([^"]+)"/i.exec(tag);
        if (!href || !href[1].startsWith('css/')) return tag;
        const source = href[1];
        const css = read(source);
        if (/@import|url\s*\(/i.test(css))
          throw new Error('Inline new CSS assets explicitly before shipping offline: ' + source);
        return `<style data-source="${source}">${css.replace(/<\/style/gi, '<\\/style')}</style>`;
      })
      .replace(/(\bhref=")(?:\.\/)?assets\/favicon\.svg(")/i, (_, before, after) => {
        const data = Buffer.from(read('assets/favicon.svg')).toString('base64');
        return `${before}data:image/svg+xml;base64,${data}${after}`;
      })
      .replace(/<script\b[^>]*\btype="module"[^>]*>\s*<\/script>/gi, '')
      .replace(/href="(?:\.\/|\/Esoterik-Welt\/)(#[^"]*)?"/g, (_, hash = '') => `href="Lokal.html${hash}"`)
      .replace(
        /href="((?:impressum|datenschutz|haftung)\.html)(#[^"]*)?"/g,
        (_, target, hash = '') => `href="${localName(target)}${hash}"`
      );
    if (file === 'index.html') {
      html = html.replace(
        '</body>',
        () =>
          `<script id="local-crystals-data" type="application/json">${json}</script>\n<script>${bundle}</script>\n</body>`
      );
    }
    html = html.replace(
      /<html lang="de"[^>]*>/i,
      (tag) => `<!-- GENERATED by npm run build. Edit the canonical sources, not this file. -->\n${tag}`
    );
    fs.writeFileSync(path.join(root, localName(file)), html);
    fs.writeFileSync(path.join(output, localName(file)), html);
  }
  fs.rmSync(bundleDir, { recursive: true, force: true });
  console.log('Offline file build ready: Lokal.html (+ generated legal pages); no module/fetch/font requests.');
}
module.exports = { buildLocal };

// `npm run build:local` is the first half of `npm run test:offline`, which checks the
// file:// edition right after building it. Without this entry point the script was a
// no-op and the offline test could silently audit a stale Lokal*.html.
if (require.main === module) {
  buildLocal(root).catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
